import {expect,test} from '@playwright/test';

test('the unified overview groups payments beside analytics and links to reproducible date filters',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-17T10:00:00Z'));
 await page.addInitScript(()=>localStorage.setItem('gharhisab-overview-layout','payments'));
 await page.goto('/');
 const feed=page.getByRole('region',{name:'Payment activity'});
 const chart=page.getByRole('region',{name:'Where the money went'});
 await expect(page.getByRole('group',{name:'Overview layout'})).toHaveCount(0);
 for(const name of ['Spending by month','Material purchase costs','Project Activity','Top material purchase costs']){
  await expect(page.getByRole('heading',{name,exact:true})).toHaveCount(0);
 }
 await expect(page.getByRole('heading',{name:'People’s contributions'})).toBeVisible();
 for(const width of [360,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  await expect(page.locator('.spent-value')).toHaveText('₹6,18,300');
  await expect(feed.getByRole('region',{name:'Paid today'}).locator('.paid-today-total')).toHaveText('₹38,500');
  await expect(feed.getByRole('region',{name:'Recent payments'})).toBeVisible();
  await expect(page.locator('.overview-categories [data-photo="materials"]')).toBeVisible();
  await expect(page.locator('.overview-cover-photo')).toBeVisible();
  await expect(chart.locator('.category-stack span').first()).toHaveCSS('transition-duration','0s');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(width);
  const [feedBox,chartBox]=await Promise.all([feed.boundingBox(),chart.boundingBox()]);
  if(width===360)expect(chartBox!.y).toBeGreaterThanOrEqual(feedBox!.y+feedBox!.height);
  else expect(feedBox!.x).toBeGreaterThan(chartBox!.x);
  await page.screenshot({path:`test-results/overview-${width}.png`,fullPage:true});
 }
 await page.getByLabel('Date range').selectOption('Last month');
 await expect(page.locator('.spent-value')).toHaveText('₹6,18,300');
 await expect(page.locator('.paid-today-total')).toHaveText('₹38,500');
 await expect(page.locator('.overview-range-total strong')).toHaveText('₹2,42,800');
 await expect(page.getByRole('region',{name:'Compare periods'})).toContainText('61% higher');
 const materials=page.getByRole('link',{name:'Materials ₹1,74,800',exact:true});
 await expect(materials).toHaveAttribute('aria-description','72% of spending');
 await materials.focus();
 await page.keyboard.press('Enter');
 await expect(page).toHaveURL(/#\/expenses\?payments=completed&from=2026-10-01&to=2026-10-31&category=Materials$/);
 await expect(page.getByLabel('Category')).toHaveValue('Materials');
 await expect(page.locator('tbody tr')).toHaveCount(3);
 await page.getByLabel('Payment method').selectOption('Bank Transfer');
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.getByLabel('Search transactions').fill('Agarwal');
 const filtered=page.url();
 await page.reload();
 await expect(page.getByLabel('Search transactions')).toHaveValue('Agarwal');
 await expect(page.getByLabel('Payment method')).toHaveValue('Bank Transfer');
 const row=page.getByRole('button',{name:'Open payment for Foundation reinforcement steel'});
 await row.focus();
 const scrollBefore=await page.evaluate(()=>window.scrollY);
 await page.keyboard.press('Enter');
 const detail=page.getByRole('dialog',{name:'Transaction details'});
 await expect(detail.locator('[data-selected=true]')).toContainText('Paid to Agarwal Steel Traders');
 await expect(detail.locator('[data-selected=true]')).toContainText('21 Oct 2026 · Bank Transfer');
 await page.keyboard.press('Escape');
 await expect(row).toBeFocused();
 expect(await page.evaluate(()=>window.scrollY)).toBe(scrollBefore);
 await page.getByRole('link',{name:'Overview',exact:true}).first().click();
 await page.goBack();
 await expect(page).toHaveURL(filtered);
 await expect(page.getByLabel('Search transactions')).toHaveValue('Agarwal');
 await page.getByRole('link',{name:'Overview',exact:true}).first().click();
 await page.getByLabel('Date range').selectOption('Last month');
 await page.getByRole('region',{name:'Compare periods'}).getByRole('link',{name:/Selected range.*1 Oct.*₹2,42,800/}).press('Enter');
 await expect(page.locator('tbody tr')).toHaveCount(4);
 await page.getByRole('button',{name:'Preview as viewer'}).click();
 await expect(page.getByRole('button',{name:'Add expense',exact:true})).toHaveCount(0);
});

test('admin confirms an intentional repeat and a backdated payment stays out of today',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-20T08:00:00Z'));
 await page.goto('/#/');
 await page.getByRole('button',{name:'Add expense',exact:true}).first().click();
 const expense=page.getByRole('dialog',{name:'Expense form'});
 await expense.getByLabel('Expense title').fill('Repeat test');
 await expense.getByLabel('Expense type').selectOption('Other');
 await expense.getByLabel('Expense date').fill('2026-11-01');
 await expense.getByLabel('Agreed total cost').fill('90000');
 await expense.getByLabel('Vendor / contractor').fill('Sharma Building Supply');
 await expense.getByRole('button',{name:'Save expense'}).click();
 await expect(expense).toHaveCount(0);
 await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Expenses'}).click();
 await page.getByLabel('Search transactions').fill('Repeat test');
 await page.getByRole('button',{name:'Open Repeat test'}).click();
 const detail=page.getByRole('dialog',{name:'Transaction details'});
 await detail.getByRole('button',{name:'Record payment'}).click();
 const editor=page.getByRole('dialog',{name:'Record payment'});
 await editor.getByLabel('Payment date').fill('2026-11-17');
 await editor.getByLabel('Amount paid').fill('38500');
 await editor.getByRole('button',{name:'Save payment'}).click();
 await expect(editor.getByRole('alert')).toContainText('Possible duplicate payment');
 await expect(detail.locator('.payment-history-row')).toHaveCount(0);
 await editor.getByRole('button',{name:'Save anyway'}).click();
 await expect(editor).toHaveCount(0);
 await expect(page.getByRole('status').filter({hasText:'Payment saved.'})).toBeVisible();
 await expect(detail.locator('.payment-history-row')).toHaveCount(1);
 await detail.getByRole('button',{name:'Close transaction details'}).click();
 await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Home'}).click();
 await expect(page.getByRole('region',{name:'Paid today'})).toContainText('No payments today');
 await expect(page.locator('.paid-today-total')).toHaveText('₹0');
});
